"""Synthesise the narration with Kokoro (82M, ONNX) and write per-line WAVs plus js/narration.js.

Usage: KOKORO_DIR=/path/to/kokoro-model-files python3 tools/tts.py [line ids...]
The model files (kokoro-v1.0.onnx, voices-v1.0.bin) come from
https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
"""
import json, os, sys
import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPT = os.path.join(ROOT, "narration", "script.json")
OUT = os.path.join(ROOT, "audio", "lines")
KDIR = os.environ.get("KOKORO_DIR", ".")


def trim(a, sr, thresh=0.006, pad=0.06):
    """Cut leading/trailing silence, keeping a short pad."""
    idx = np.where(np.abs(a) > thresh)[0]
    if not len(idx):
        return a
    s = max(0, idx[0] - int(pad * sr))
    e = min(len(a), idx[-1] + int(pad * sr))
    return a[s:e]


def main():
    spec = json.load(open(SCRIPT))
    voice, speed = spec.get("voice", "bm_george"), spec.get("speed", 0.94)
    lang = "en-gb" if voice.startswith("b") else "en-us"
    only = set(sys.argv[1:])
    os.makedirs(OUT, exist_ok=True)
    k = Kokoro(os.path.join(KDIR, "kokoro-v1.0.onnx"), os.path.join(KDIR, "voices-v1.0.bin"))
    meta = {}
    for line in spec["lines"]:
        lid, text = line["id"], line["text"]
        path = os.path.join(OUT, f"{lid}.wav")
        if not only or lid in only or not os.path.exists(path):
            say = line.get("say", text)
            a, sr = k.create(say, voice=line.get("voice", voice), speed=line.get("speed", speed), lang=lang)
            a = trim(np.asarray(a, dtype=np.float32), sr)
            sf.write(path, a, sr, subtype="PCM_16")
        info = sf.info(path)
        meta[lid] = {"text": text, "dur": round(info.frames / info.samplerate, 3)}
        print(f"{lid} {meta[lid]['dur']:6.2f}s  {text[:70]}")
    total = sum(m["dur"] for m in meta.values())
    with open(os.path.join(ROOT, "js", "narration.js"), "w") as f:
        f.write("// Generated by tools/tts.py: narration text and measured line durations (seconds).\n")
        f.write("window.NARRATION = " + json.dumps({"voice": voice, "lines": meta}, ensure_ascii=False, indent=1) + ";\n")
    print(f"{len(meta)} lines, {total:.1f}s of speech")


if __name__ == "__main__":
    main()
